let pool: Pool | null = null;
let ready: Promise<void> | null = null;

export function pgPoolConfig(url: string): PoolConfig {
  return {
    connectionString: url,
    max: 5,
    connectionTimeoutMillis: 5_000,
    idleTimeoutMillis: 30_000,
    // PG-MIGRATE r2 (J1 M2 / J2 m2): shorter caps — a stalled DB must
    // not hold a request for 12 s + a 12 s ROLLBACK. Request-path WRITES
    // are additionally bounded at STORAGE_WRITE_DEADLINE_MS in
    // core/storage.ts; these caps bound reads and background batches.
    statement_timeout: 5_000,
    query_timeout: 6_000,
    keepAlive: true,
    // r3 (J2-r2 H1): a session that dies or stalls mid-transaction (e.g. a
    // partition after BEGIN, or a client that destroyed its socket without
    // the FIN reaching the server) must not keep its locks/transaction open
    // for hours: the server ends it after 15 s idle in a transaction.
    idle_in_transaction_session_timeout: 15_000,
    application_name: "verireceipt",
  };
}

function getPool(): Pool {
  if (pool) return pool;
  const url = (process.env.DATABASE_URL ?? "").trim();
  if (!url) throw new Error("verireceipt: DATABASE_URL is not set (postgres backend)");
  const p = new Pool(pgPoolConfig(url));
  // An idle client losing its connection emits 'error' on the pool; an
  // unhandled 'error' event would crash the process. Log (redacted) and
  // let the pool replace the client.
  p.on("error", (err) => {
    console.error(redactSecrets(`verireceipt: postgres idle client error: ${err.message}`, [url]));
  });
  // PG-MIGRATE r3 (J1-r2 H1): pg-pool REMOVES its idle 'error' listener
  // while a client is checked out (tx(), ensurePgReady(), and pool.query()
  // between its own once-listener's removal and release). A backend
  // termination (Render maintenance/restart/failover: 57P01, or a reset)
  // makes the Client emit 'error'; with no listener Node throws and the
  // whole process exits 1. Attach one permanent listener to EVERY client
  // the pool creates, so a dropped connection only fails the operation
  // that was using it (its query rejects; tx() then destroys the client).
  p.on("connect", (client) => attachClientErrorGuard(client, url));
  pool = p;
  return p;
}

const GUARDED = Symbol.for("verireceipt.pgClientErrorGuard");

/** Idempotent: one 'error' listener per pg Client for its whole life (logs a redacted line). */
export function attachClientErrorGuard(
  client: { on: (ev: "error", fn: (err: Error) => void) => unknown },
  secret = "",
): void {
  const c = client as unknown as Record<symbol, boolean>;
  if (c[GUARDED]) return;
  c[GUARDED] = true;
  client.on("error", (err: Error) => {
    console.error(
      redactSecrets(
        `verireceipt: postgres connection lost (${(err as { code?: string }).code ?? "error"}): ${err.message}`,
        [secret],
      ),
    );
  });
}

/** Test hook (r3): called inside the schema-setup / write transactions after BEGIN, with the client's backend pid. */
let txPauseForTests: ((where: "schema" | "tx", pid: number) => Promise<void>) | null = null;
export function __setPgTxPauseForTests(fn: ((where: "schema" | "tx", pid: number) => Promise<void>) | null): void {
  txPauseForTests = fn;
}
const pidOf = (c: PoolClient) => (c as unknown as { processID?: number }).processID ?? -1;

/** Create the schema (idempotent, advisory-locked). Memoised; a failure is retried on the next call. */
export function ensurePgReady(): Promise<void> {
  if (ready) return ready;
  ready = (async () => {
    const client = await getPool().connect();
    attachClientErrorGuard(client); // belt-and-braces: the pool 'connect' hook already did
    try {
      await client.query("BEGIN");
      if (txPauseForTests) await txPauseForTests("schema", pidOf(client));
      await client.query("SELECT pg_advisory_xact_lock($1)", [SCHEMA_LOCK_KEY]);
      await client.query(PG_SCHEMA_SQL);
      await client.query("COMMIT");
      client.release();
    } catch (err) {
      // r3: same bounded-rollback + destroy as tx() (a dead socket must
      // neither hang boot nor go back to the pool).
      await rollbackBounded(client);
      client.release(err instanceof Error ? err : new Error(String(err)));
      throw err;
    }
  })();
  ready.catch(() => {
    ready = null;
  });
  return ready;
}

async function q<T = Record<string, unknown>>(sql: string, params: unknown[] = []): Promise<T[]> {
  await ensurePgReady();
  const res = await getPool().query(sql, params);
  return res.rows as T[];
}

/** Max wait for a ROLLBACK after a failed transaction (the socket may be dead). */
const ROLLBACK_WAIT_MS = 500;

async function rollbackBounded(client: PoolClient): Promise<void> {
  let t: NodeJS.Timeout | undefined;
  await Promise.race([
    client.query("ROLLBACK").catch(() => undefined),
    new Promise<void>((r) => {
      t = setTimeout(r, ROLLBACK_WAIT_MS);
      if (typeof t.unref === "function") t.unref();
    }),
  ]);
  if (t) clearTimeout(t);
}

async function tx<T>(fn: (c: PoolClient) => Promise<T>): Promise<T> {
  await ensurePgReady();
  const client = await getPool().connect();
  attachClientErrorGuard(client); // belt-and-braces: the pool 'connect' hook already did
  try {
    await client.query("BEGIN");
    if (txPauseForTests) await txPauseForTests("tx", pidOf(client));
    const out = await fn(client);
    await client.query("COMMIT");
    client.release();
    return out;
  } catch (err) {
    // PG-MIGRATE r2 (J1 M2 / J2 m2): never wait 12 s for a ROLLBACK on a
    // stalled socket, and never hand a client that failed mid-transaction
    // back to the pool: release(err) DESTROYS it (the server rolls back
    // an aborted session's open transaction when the socket closes).
    await rollbackBounded(client);
    client.release(err instanceof Error ? err : new Error(String(err)));
    throw err;
  }
}

/** NUL can never be stored in a Postgres TEXT column; no stored key contains one. */
const hasNul = (...xs: Array<string | null | undefined>) => xs.some((x) => typeof x === "string" && x.includes("\u0000"));

/** Fast liveness probe: one `SELECT 1` (no table access). Resolves to round-trip ms. */
export async function pgPing(): Promise<number> {
  const t0 = Date.now();
  await getPool().query("SELECT 1");
  return Date.now() - t0;
}

/** End the pool (graceful shutdown). Safe to call twice. */
/** Cap on pool.end() during shutdown (J2 M1): a stalled socket must not hold the exit. */
export const PG_CLOSE_WAIT_MS = 3_000;

export async function closePg(): Promise<void> {
  const p = pool;
  pool = null;
  ready = null;
  if (!p) return;
  let t: NodeJS.Timeout | undefined;
  await Promise.race([
    p.end().catch(() => undefined),
    new Promise<void>((r) => {
      t = setTimeout(r, PG_CLOSE_WAIT_MS);
      if (typeof t.unref === "function") t.unref();
    }),
  ]);
  if (t) clearTimeout(t);
}

