export async function getGridPricePg(
  nodeOrZone: string,
  intervalStart: string,
): Promise<{ lmp_usd_per_mwh: number; market: string; ingested_at: string; upstream_url: string } | null> {
  if (hasNul(nodeOrZone, intervalStart)) return null;
  const [row] = await q<{ lmp_usd_per_mwh: number; market: string; ingested_at: string; upstream_url: string }>(
    `SELECT lmp_usd_per_mwh, market, ingested_at, upstream_url FROM grid_cache
     WHERE node_or_zone = $1 AND interval_start = $2`,
    [nodeOrZone, intervalStart],
  );
  if (!row) return null;
  return {
    lmp_usd_per_mwh: row.lmp_usd_per_mwh,
    market: row.market,
    ingested_at: row.ingested_at ?? "",
    upstream_url: row.upstream_url ?? "",
  };
}

const UPSERT_GRID_SQL = `INSERT INTO grid_cache
  (node_or_zone, interval_start, lmp_usd_per_mwh, market, ingested_at, upstream_url)
  SELECT * FROM unnest($1::text[], $2::text[], $3::float8[], $4::text[], $5::text[], $6::text[])
  ON CONFLICT (node_or_zone, interval_start) DO UPDATE SET
    lmp_usd_per_mwh = excluded.lmp_usd_per_mwh,
    market = excluded.market,
    ingested_at = excluded.ingested_at,
    upstream_url = excluded.upstream_url`;

const UPSERT_REVALIDATE_SUCCESS_SQL = `INSERT INTO grid_cache_revalidate
  (node_or_zone, interval_start, last_success_at, last_attempt_at)
  SELECT n, i, a, a FROM unnest($1::text[], $2::text[], $3::text[]) AS v(n, i, a)
  ON CONFLICT (node_or_zone, interval_start) DO UPDATE SET
    last_success_at = excluded.last_success_at,
    last_attempt_at = excluded.last_attempt_at`;

const GRID_CHUNK = 1_000;

/**
 * Write pre-validated grid rows in ONE transaction (chunked multi-row
 * upserts), then mark each key revalidated and bound the table — the
 * Postgres twin of jobs/gridIngester saveGridPriceBatch. SQLite's
 * per-row INSERT OR REPLACE lets a later duplicate key in the same batch
 * win; a single Postgres upsert cannot touch one row twice, so the batch
 * is first de-duplicated keeping the LAST occurrence (same result).
 */
export async function saveGridPriceRowsPg(rows: PgGridPriceRow[]): Promise<void> {
  if (rows.length === 0) return;
  const last = new Map<string, PgGridPriceRow>();
  for (const r of rows) {
    const k = r.node + "\u0000" + r.intervalStart;
    last.delete(k);
    last.set(k, r);
  }
  const uniq = [...last.values()];
  await tx(async (c) => {
    for (let i = 0; i < uniq.length; i += GRID_CHUNK) {
      const part = uniq.slice(i, i + GRID_CHUNK);
      await c.query(UPSERT_GRID_SQL, [
        part.map((r) => r.node),
        part.map((r) => r.intervalStart),
        part.map((r) => r.lmp),
        part.map((r) => r.market),
        part.map((r) => r.ingestedAt),
        part.map((r) => r.upstreamUrl),
      ]);
      await c.query(UPSERT_REVALIDATE_SUCCESS_SQL, [
        part.map((r) => r.node),
        part.map((r) => r.intervalStart),
        part.map((r) => r.ingestedAt),
      ]);
    }
  });
  await purgeGridCacheOverflowPg();
}

export async function saveGridPricePg(
  nodeOrZone: string,
  intervalStart: string,
  lmp: number,
  market: string,
  ingestedAt?: string,
  upstreamUrl?: string,
): Promise<void> {
  validateGridPriceWrite(nodeOrZone, intervalStart, lmp, market);
  if ([ingestedAt, upstreamUrl].some((v) => typeof v === "string" && v.includes("\u0000"))) {
    throw new Error("saveGridPrice refuses a NUL character in ingested_at or upstream_url");
  }
  const at = ingestedAt ?? new Date().toISOString();
  await tx(async (c) => {
    await c.query(UPSERT_GRID_SQL, [[nodeOrZone], [intervalStart], [lmp], [market], [at], [upstreamUrl ?? ""]]);
    await c.query(UPSERT_REVALIDATE_SUCCESS_SQL, [[nodeOrZone], [intervalStart], [ingestedAt ?? new Date().toISOString()]]);
  });
  await purgeGridCacheOverflowPg();
}

export async function getGridRevalidatePg(
  nodeOrZone: string,
  intervalStart: string,
): Promise<GridRevalidateState | null> {
  if (hasNul(nodeOrZone, intervalStart)) return null;
  const [row] = await q<GridRevalidateState>(
    `SELECT last_success_at, last_attempt_at FROM grid_cache_revalidate
     WHERE node_or_zone = $1 AND interval_start = $2`,
    [nodeOrZone, intervalStart],
  );
  return row ?? null;
}

