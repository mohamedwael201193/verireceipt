// PG-MIGRATE (2026-11-21): Postgres storage backend.
//
// WHY THIS EXISTS: the SQLite file lived on a Render persistent disk, and
// a disk makes Render stop the old instance BEFORE starting the new one
// on every deploy (render.com/docs/disks, "Disk limitations") — a ~25 s
// /health outage per deploy (incident 2026-11-21 15:16 Cairo). With
// storage in Render Postgres the disk can be removed, and Render keeps
// the old instance serving until the new one passes /health.
//
// SEMANTICS ARE THE SQLITE ONES, NOT NEW ONES. Every validation, gzip
// step, budget rule, decode check and eviction choice is the SAME
// function the SQLite backend uses (prepareReceiptWrite,
// decodeEvidenceRow, validateGridPriceWrite, selectGridEvictions in
// src/core/db.ts). What differs is only the SQL:
//   * INSERT OR IGNORE        -> INSERT ... ON CONFLICT DO NOTHING
//     (receipts stay immutable: a colliding id never rewrites a row, and
//     pages are written only when THIS call created the receipt row);
//   * INSERT OR REPLACE       -> INSERT ... ON CONFLICT DO UPDATE (grid
//     cache; every column is replaced, as REPLACE did);
//   * rowid tie-break         -> seq (identity, insertion order; the
//     migration copies SQLite's rowid into it);
//   * BLOB                    -> bytea (the gzipped bytes are stored and
//     returned byte-for-byte; raw_response_sha256 is never recomputed
//     from anything but the decompressed stored bytes);
//   * text ORDER BY           -> COLLATE "C" (byte order, = SQLite's
//     BINARY collation; the DB's locale collation could reorder
//     fetched_at ties).
// All I/O is async (node-postgres pool): nothing here blocks the event
// loop for a network round trip.

